"""Rebuild public/icons.svg and src/icon-names.ts from icons-src/ (Phosphor, MIT).

Run after adding an icon: python3 scripts/build-sprite.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
icons = sorted((ROOT / "icons-src").glob("*.svg"))
symbols = []
for path in icons:
    svg = path.read_text(encoding="utf-8")
    view_box = svg.split('viewBox="', 1)[1].split('"', 1)[0]
    inner = svg.split(">", 1)[1].rsplit("</svg>", 1)[0]
    symbols.append(f'<symbol id="i-{path.stem}" viewBox="{view_box}">{inner}</symbol>')
(ROOT / "public" / "icons.svg").write_text('<svg xmlns="http://www.w3.org/2000/svg">' + "".join(symbols) + "</svg>")
names = "\n".join(f'  | "{p.stem}"' for p in icons)
(ROOT / "src" / "icon-names.ts").write_text(
    "// Generated by scripts/build-sprite.py from icons-src (Phosphor, MIT). Do not edit.\n"
    f"export type IconName =\n{names};\n"
)
print(f"{len(icons)} icons")
